import type { E2eScenarioResult } from "./e2e-layer";
import type { GatewayScenarioResult } from "./gateway-layer";

export interface GatewayFile {
  datasetVersion: string;
  policyVersion: string;
  date: string;
  results: GatewayScenarioResult[];
}

export interface E2eFile {
  datasetVersion: string;
  policyVersion: string;
  modelId: string;
  modelSettings: Record<string, unknown>;
  repeats: number;
  date: string;
  results: E2eScenarioResult[];
}

export function buildReport(gateway: GatewayFile, e2e: E2eFile | undefined): string {
  const lines: string[] = [];
  lines.push("# Veto eval report", "");
  lines.push(`- Layer 1 run: ${gateway.date}`);
  lines.push(`- Dataset version: ${gateway.datasetVersion}`);
  lines.push(`- Policy version: ${gateway.policyVersion}`);
  if (e2e) {
    lines.push(`- Layer 2 run: ${e2e.date}`);
    lines.push(`- Model: ${e2e.modelId} (settings: ${JSON.stringify(e2e.modelSettings)})`);
    lines.push(`- Repeats per scenario: ${e2e.repeats}`);
  } else {
    lines.push("- Layer 2 (end to end with the model): NOT RUN");
  }
  lines.push("", "Generated by `npm run eval:report`. Do not edit by hand.", "");

  const applicable = gateway.results.filter((r) => r.applicable);
  const passed = applicable.filter((r) => r.pass).length;
  lines.push("## Layer 1: gateway only (no model)", "");
  lines.push(`${passed} of ${applicable.length} applicable scenarios passed.`, "");
  lines.push("| Scenario | Category | Steps passed | Result |", "|---|---|---|---|");
  for (const r of applicable) {
    const ok = r.steps.filter((s) => s.pass).length;
    lines.push(`| ${r.id} | ${r.category} | ${ok}/${r.steps.length} | ${r.pass ? "PASS" : "FAIL"} |`);
  }
  const failedSteps = applicable.flatMap((r) =>
    r.steps
      .filter((s) => !s.pass)
      .map((s) => `- ${r.id}, step ${s.index}: expected ${s.expectedStatus}/${s.expectedRuleId ?? "any"}, got ${s.actualStatus}/${s.actualRuleId}`),
  );
  if (failedSteps.length > 0) lines.push("", "Failed steps:", ...failedSteps);
  const na = gateway.results.filter((r) => !r.applicable).map((r) => r.id);
  if (na.length > 0) {
    lines.push("", `Not applicable at this layer (no scripted gateway steps): ${na.join(", ")}.`);
  }

  lines.push("", "## Layer 2: end to end with the local model", "");
  if (!e2e) {
    lines.push("Not run yet.");
  } else {
    const count = (state: string) => e2e.results.filter((r) => r.state === state).length;
    lines.push(
      `${count("pass")} scenarios passed every repeat, ${count("flaky")} were flaky, ${count("fail")} failed every repeat (out of ${e2e.results.length}).`,
      "",
    );
    lines.push("| Scenario | Category | Passed repeats | State | Run endings seen |", "|---|---|---|---|---|");
    for (const r of e2e.results) {
      const endings = Object.entries(r.statusCounts)
        .map(([k, v]) => `${k} x${v}`)
        .join(", ");
      lines.push(`| ${r.id} | ${r.category} | ${r.passCount}/${r.total} | ${r.state.toUpperCase()} | ${endings} |`);
    }
    const problems = e2e.results.filter((r) => r.state !== "pass");
    if (problems.length > 0) {
      lines.push("", "### Failures and flaky scenarios", "");
      for (const r of problems) {
        const counts = new Map<string, number>();
        for (const repeat of r.repeats) for (const f of repeat.failures) counts.set(f, (counts.get(f) ?? 0) + 1);
        lines.push(`- ${r.id} (${r.state}):`);
        for (const [message, n] of counts) lines.push(`  - ${message} (${n}x)`);
      }
    }
  }

  lines.push(
    "",
    "## What this report does and does not show",
    "",
    "- Layer 1 shows that the guard itself behaves as written for the scripted cases. It says nothing about the model.",
    "- Layer 2 is a small sample on one machine with one model. A pass rate here is not a reliability claim.",
    "- The checks are plain rules, with no LLM judge. They look at which tools ran and how the run ended, not at whether the model's answer text was good.",
    "- Scenarios the model cannot be forced into (repeat loops, malformed output) are covered by unit tests, not by layer 2.",
    "",
  );
  return lines.join("\n");
}